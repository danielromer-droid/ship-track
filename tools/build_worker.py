#!/usr/bin/env python3
"""Bundle the whole app (page, styles, script, map outline, icons and API) into one
Cloudflare Worker file, dist/worker.js, that can be pasted into the Cloudflare dashboard.
No Node.js needed: run `python3 tools/build_worker.py` after editing public/ or functions/."""
import base64, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
PUB = ROOT / "public"
TYPES = {".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
         ".json": "application/json", ".svg": "image/svg+xml", ".png": "image/png", ".webmanifest": "application/manifest+json"}

assets = {}
for f in sorted(PUB.rglob("*")):
    if not f.is_file() or f.suffix not in TYPES:
        continue
    path = "/" + f.relative_to(PUB).as_posix()
    if f.suffix == ".png":
        assets[path] = [TYPES[f.suffix], base64.b64encode(f.read_bytes()).decode(), 1]
    else:
        assets[path] = [TYPES[f.suffix], f.read_text(encoding="utf-8"), 0]
assets["/"] = assets["/index.html"]

def module(p, rename=None):
    s = (ROOT / p).read_text(encoding="utf-8")
    s = re.sub(r"^import .*?;\n", "", s, flags=re.M)
    s = re.sub(r"^export (const|async function|function) ", r"\1 ", s, flags=re.M)
    if rename:
        s = s.replace("onRequestGet", rename)
    return f"// ---- {p} ----\n{s}\n"

api = module("lib/util.js") + module("functions/api/health.js", "healthGet") + module("functions/api/stream.js", "streamGet")

worker = f"""// Ship Track: the whole app in one Cloudflare Worker.
// Generated by tools/build_worker.py from public/ and functions/. Edit those, then rebuild.
{api}
const ASSETS = {json.dumps(assets, ensure_ascii=False)};

export default {{
  async fetch(request, env, ctx) {{
    const url = new URL(request.url);
    const c = {{ request, env: env || {{}}, waitUntil: (p) => ctx.waitUntil(p) }};
    if (url.pathname === "/api/health") return healthGet(c);
    if (url.pathname === "/api/stream") return streamGet(c);
    const a = ASSETS[url.pathname];
    if (!a) return new Response("Not found", {{ status: 404 }});
    const body = a[2] ? Uint8Array.from(atob(a[1]), (ch) => ch.charCodeAt(0)) : a[1];
    return new Response(body, {{ headers: {{ "content-type": a[0], "cache-control": url.pathname === "/sw.js" ? "no-cache" : "public, max-age=300" }} }});
  }},
}};
"""
out = ROOT / "dist" / "worker.js"
out.parent.mkdir(exist_ok=True)
out.write_text(worker, encoding="utf-8")
print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
